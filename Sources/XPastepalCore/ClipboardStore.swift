    public init(directory: URL? = nil, pasteboard: NSPasteboard = .general, monitoring: Bool? = nil,
                sourceIconProvider: ((String) -> Data?)? = nil) {
        self.directory = directory ?? FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask)[0]
            .appendingPathComponent("XPastepal", isDirectory: true)
        self.pasteboard = pasteboard
        self.sourceIconProvider = sourceIconProvider ?? { SourceAppIconProvider.shared.iconData(for: $0) }
        lastChangeCount = pasteboard.changeCount
        loadHistory()
        reconcileSyncState()
        isLoading = false
        let beforePruning = items
        applyLimits()
        if beforePruning != items { save() }
        // 显式参数只控制当前实例，测试与演示不会改写用户保存的选择。
        if monitoring ?? monitoringPreference { startMonitoring(persistPreference: false) }
    }

    public func startMonitoring(persistPreference: Bool = true) {
        if persistPreference && !monitoringPreference {
            monitoringPreference = true
            save()
        }
        guard !isMonitoring else { return }
        // 启动和恢复时只记住版本号，不采集暂停期间或启动之前的内容。
        lastChangeCount = pasteboard.changeCount
        isMonitoring = true
        let pollTimer = Timer(timeInterval: 0.6, repeats: true) { [weak self] _ in
            Task { @MainActor [weak self] in self?.pollClipboard() }
        }
        timer = pollTimer
        RunLoop.main.add(pollTimer, forMode: .common)
    }

    public func stopMonitoring(persistPreference: Bool = true) {
        timer?.invalidate()
        timer = nil
        isMonitoring = false
        if persistPreference && monitoringPreference {
            monitoringPreference = false
            save()
        }
    }

    /// 参数供测试或显式导入使用；日常采集会读取当前前台应用。
    public func captureCurrentClipboard(sourceApp: String? = nil, sourceBundleID: String? = nil) {
        lastChangeCount = pasteboard.changeCount
        let frontmost = NSWorkspace.shared.frontmostApplication
        let appName = sourceApp ?? frontmost?.localizedName ?? "未知应用"
        let bundleID = sourceBundleID ?? frontmost?.bundleIdentifier ?? ""
        guard !isExcluded(bundleID: bundleID) else { return }
        let availableTypes = Set((pasteboard.types ?? []).map(\.rawValue))
        guard availableTypes.isDisjoint(with: Self.privatePasteboardTypes) else { return }

        let now = Date()
        var newItem: ClipItem
        let fileURLs = (pasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL]) ?? []
        if !fileURLs.isEmpty {
            let paths = fileURLs.map { $0.standardizedFileURL.path }
            newItem = ClipItem(createdAt: now, text: paths.joined(separator: "\n"), kind: .file,
                               sourceApp: appName, sourceBundleID: bundleID, filePaths: paths)
        } else if let imageData = readImageData() {
            guard imageData.count <= Self.maximumPayloadBytes else {
                lastAction = "已跳过超过 25 MB 的图片"
                return
            }
            newItem = ClipItem(createdAt: now, text: "", kind: .image,
                               sourceApp: appName, sourceBundleID: bundleID, imageData: imageData)
        } else {
            let rtf = pasteboard.data(forType: .rtf)
            guard (rtf?.count ?? 0) <= Self.maximumPayloadBytes else {
                lastAction = "已跳过超过 25 MB 的富文本"
                return
            }
            let plainText = pasteboard.string(forType: .string) ?? pasteboard.string(forType: .URL) ?? rtf.flatMap {
                try? NSAttributedString(data: $0, options: [.documentType: NSAttributedString.DocumentType.rtf], documentAttributes: nil).string
            }
            guard let plainText, !plainText.isEmpty else { return }
            guard plainText.utf8.count <= Self.maximumPayloadBytes else {
                lastAction = "已跳过超过 25 MB 的文本"
                return
            }
            newItem = ClipItem(createdAt: now, text: plainText, kind: Self.kind(for: plainText),
                               sourceApp: appName, sourceBundleID: bundleID, rtfData: rtf)
        }

        newItem.sourceIconData = sourceIconData(for: bundleID)
        if let oldIndex = items.firstIndex(where: { Self.hasSameContent($0, newItem) }) {
            let previous = items.remove(at: oldIndex)
            newItem.id = previous.id
            newItem.createdAt = previous.createdAt
            newItem.isPinned = previous.isPinned
            newItem.collectionID = previous.collectionID
            if newItem.sourceIconData == nil, previous.sourceBundleID == bundleID {
                newItem.sourceIconData = previous.sourceIconData
            }
        }
        items.insert(newItem, at: 0)
        applyLimits()
        save()
        onCapture?(newItem)
    }

    /// `reorder` 为 false 时只更新使用时间，位置调整推迟到 `applyDeferredReorder()`。
    @discardableResult
    public func copy(_ item: ClipItem, plainText: Bool = false, reorder: Bool = true) -> Bool {
        let content = items.first(where: { $0.id == item.id }) ?? item
        let boardItem = NSPasteboardItem()
        if plainText {
            guard !content.text.isEmpty else { return false }
            boardItem.setString(content.text, forType: .string)
        } else {
            switch content.kind {
            case .file:
                let urls = content.filePaths.map { NSURL(fileURLWithPath: $0) }
                guard !urls.isEmpty else { return false }
                pasteboard.clearContents()
                let success = pasteboard.writeObjects(urls)
                lastChangeCount = pasteboard.changeCount
                if success { markCopied(content, reorder: reorder) }
                return success
            case .image:
                guard let data = content.imageData, !data.isEmpty else { return false }
                boardItem.setData(data, forType: Self.imageType(for: data))
            case .text, .link:
                boardItem.setString(content.text, forType: .string)
                if let rtf = content.rtfData { boardItem.setData(rtf, forType: .rtf) }
                if content.kind == .link { boardItem.setString(content.text, forType: .URL) }
            }
        }
        pasteboard.clearContents()
        let success = pasteboard.writeObjects([boardItem])
        lastChangeCount = pasteboard.changeCount
        if success { markCopied(content, reorder: reorder) }
        return success
    }

    public func togglePin(_ item: ClipItem) {
