    }

    /// 从编辑器、OCR 或其他应用内操作添加文本，不改写系统剪贴板。
    @discardableResult
    public func addText(_ text: String, sourceApp: String = "XPastepal") -> ClipItem? {
        guard !text.isEmpty, text.utf8.count <= Self.maximumPayloadBytes else {
            errorMessage = "文本不能为空或超过 25 MB"
            return nil
        }
        var item = ClipItem(text: text, kind: Self.kind(for: text), sourceApp: sourceApp,
                            sourceBundleID: "milu.pastepal", sourceIconData: sourceIconData(for: "milu.pastepal"))
        if let index = items.firstIndex(where: { Self.hasSameContent($0, item) }) {
            let previous = items.remove(at: index)
            item.id = previous.id
            item.createdAt = previous.createdAt
            item.isPinned = previous.isPinned
            item.collectionID = previous.collectionID
            if item.sourceIconData == nil, previous.sourceBundleID == item.sourceBundleID {
                item.sourceIconData = previous.sourceIconData
            }
        }
        items.insert(item, at: 0)
        applyLimits()
        save()
        lastAction = "已添加文本"
        return item
    }

    /// 转换结果作为独立记录保存；无变化时直接返回原记录。
    @discardableResult
    public func transform(_ item: ClipItem, using transformation: TextTransformation) -> ClipItem? {
        let content = items.first(where: { $0.id == item.id }) ?? item
        guard [.text, .link].contains(content.kind) else { return nil }
        let result = transformation.apply(to: content.text)
        guard !result.isEmpty else {
            lastAction = "转换后没有可保存的文本"
            return nil
        }
        guard result != content.text else {
            lastAction = "文本无需转换"
            return content
        }
        guard result.utf8.count <= Self.maximumPayloadBytes else {
            errorMessage = "转换结果超过 25 MB"
            return nil
        }
        if let existing = items.first(where: { [.text, .link].contains($0.kind) && $0.text == result }) {
            lastAction = "转换结果已在历史中"
            return existing
        }
        guard items.count < 20_000 else {
            errorMessage = "历史已达 20,000 条，请整理后再创建转换结果"
            return nil
        }
        let transformed = ClipItem(text: result, kind: Self.kind(for: result), sourceApp: "XPastepal",
                                   sourceBundleID: "milu.pastepal", sourceIconData: sourceIconData(for: "milu.pastepal"),
                                   collectionID: content.collectionID)
        let ordinaryBytes = items.filter { !$0.isPinned }.reduce(0) { $0 + HistoryArchive.payloadBytes($1) }
        guard ordinaryBytes + HistoryArchive.payloadBytes(transformed) <= Self.maximumUnpinnedPayloadBytes else {
            errorMessage = "普通历史已达 128 MB，请整理后再创建转换结果"
            return nil
        }
        // 显式转换保留原记录；达到条数上限时扩充一条，后续自动采集继续遵循设置。
        isLoading = true
        maxItems = max(maxItems, items.count + 1)
        isLoading = false
        items.insert(transformed, at: 0)
        save()
        lastAction = "已\(transformation.title)，原记录已保留"
        return transformed
    }

    public func recognizeText(in item: ClipItem) async -> String? {
        let content = items.first(where: { $0.id == item.id }) ?? item
        guard content.kind == .image, let data = content.imageData, !data.isEmpty else {
            errorMessage = "请选择包含图片数据的记录"
            return nil
        }
        guard data.count <= Self.maximumPayloadBytes else {
            errorMessage = "图片超过 25 MB，无法识别"
            return nil
        }
        do {
            let text = try await Task.detached(priority: .userInitiated) {
                try TextRecognition.recognize(data)
            }.value
            guard !Task.isCancelled else { return nil }
            lastAction = text.isEmpty ? "图片中未识别到文字" : "已识别 \(text.count) 个字符"
            return text.isEmpty ? nil : text
        } catch {
            errorMessage = "图片文字识别失败：\(error.localizedDescription)"
            return nil
        }
    }

    /// 多选文本按传入顺序连接，一次性写入剪贴板，不产生重复采集。
    @discardableResult
    public func copyItems(_ selectedItems: [ClipItem], separator: String = "\n", reorder: Bool = true) -> Bool {
        var seen = Set<UUID>()
        let currentByID = Dictionary(items.map { ($0.id, $0) }, uniquingKeysWith: { first, _ in first })
        let content = selectedItems.filter { seen.insert($0.id).inserted }.map { currentByID[$0.id] ?? $0 }
        guard !content.isEmpty else { return false }
        if content.count == 1 { return copy(content[0], reorder: reorder) }
        guard content.allSatisfy({ [.text, .link].contains($0.kind) }) else {
            errorMessage = "合并复制仅支持文本和链接"
            return false
        }
        let textBytes = content.reduce(0) { $0 + $1.text.utf8.count }
        let separatorBytes = separator.utf8.count.multipliedReportingOverflow(by: max(0, content.count - 1))
        guard !separatorBytes.overflow, separatorBytes.partialValue <= Self.maximumPayloadBytes,
              textBytes <= Self.maximumPayloadBytes - separatorBytes.partialValue else {
            errorMessage = "合并后的文本超过 25 MB"
            return false
        }
        let text = content.map(\.text).joined(separator: separator)
        pasteboard.clearContents()
        let success = pasteboard.setString(text, forType: .string)
        lastChangeCount = pasteboard.changeCount
        guard success else { errorMessage = "无法写入剪贴板"; return false }
        let ids = Set(content.map(\.id))
        let now = Date()
        if reorder {
            let updated = content.filter { currentByID[$0.id] != nil }.map { value in
                var item = value
                item.lastCopiedAt = now
                return item
            }
            items.removeAll { ids.contains($0.id) }
            items.insert(contentsOf: updated, at: 0)
        } else {
            for index in items.indices where ids.contains(items[index].id) { items[index].lastCopiedAt = now }
            // 同一时间戳按选择顺序排列，与立即重排的结果一致。
            deferredReorderIDs.removeAll { ids.contains($0) }
            deferredReorderIDs.insert(contentsOf: content.map(\.id), at: 0)
        }
        save()
        lastAction = "已合并复制 \(content.count) 条记录"
        return true
    }

    public func delete(_ item: ClipItem) {
        items.removeAll { $0.id == item.id }
