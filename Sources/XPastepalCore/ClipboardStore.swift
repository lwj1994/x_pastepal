    public func delete(ids: Set<UUID>) {
        let previousCount = items.count
        items.removeAll { ids.contains($0.id) }
        guard items.count != previousCount else { return }
        lastAction = "已删除 \(previousCount - items.count) 条记录"
        save()
    }

    public func clearUnpinned() {
        items.removeAll { !$0.isPinned }
        lastAction = "已清除未固定的历史"
        save()
    }

    public func addCollection(name: String) {
        let cleanName = name.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !cleanName.isEmpty, cleanName.utf8.count <= 1_000, collections.count < 1_000 else { return }
        guard !collections.contains(where: { $0.name.localizedCaseInsensitiveCompare(cleanName) == .orderedSame }) else {
            lastAction = "该收藏夹已存在"
            return
        }
        collections.append(ClipCollection(name: cleanName))
        save()
    }

    @discardableResult
    public func renameCollection(_ collection: ClipCollection, name: String) -> Bool {
        let cleanName = name.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !cleanName.isEmpty, cleanName.utf8.count <= 1_000,
              let index = collections.firstIndex(where: { $0.id == collection.id }) else { return false }
        guard !collections.contains(where: { $0.id != collection.id && $0.name.localizedCaseInsensitiveCompare(cleanName) == .orderedSame }) else {
            errorMessage = "已存在同名收藏夹"
            return false
        }
        collections[index].name = cleanName
        save()
        lastAction = "已重命名收藏夹"
        return true
    }

    public func deleteCollection(_ collection: ClipCollection) {
        collections.removeAll { $0.id == collection.id }
        for index in items.indices where items[index].collectionID == collection.id {
            items[index].collectionID = nil
        }
        save()
    }

    public func move(_ item: ClipItem, to collectionID: UUID?) {
        guard collectionID == nil || collections.contains(where: { $0.id == collectionID }) else { return }
        guard let index = items.firstIndex(where: { $0.id == item.id }) else { return }
        items[index].collectionID = collectionID
        save()
    }

    public func move(ids: Set<UUID>, to collectionID: UUID?) {
        guard collectionID == nil || collections.contains(where: { $0.id == collectionID }) else { return }
        var movedCount = 0
        for index in items.indices where ids.contains(items[index].id) {
            items[index].collectionID = collectionID
            movedCount += 1
        }
        guard movedCount > 0 else { return }
        save()
        lastAction = "已移动 \(movedCount) 条记录"
    }

    public func exportHistory(to url: URL) async throws {
        var snapshot = currentSnapshot()
        snapshot.syncState = nil
        snapshot.cloudSyncEnabled = nil
        snapshot.cloudAccountID = nil
        let accessing = url.startAccessingSecurityScopedResource()
        defer { if accessing { url.stopAccessingSecurityScopedResource() } }
        do {
            try await Task.detached(priority: .utility) {
                try HistoryArchive.write(snapshot, to: url, enforceArchiveLimit: true)
            }.value
            lastAction = "已导出 \(snapshot.items.count) 条记录"
        } catch {
            errorMessage = "导出失败：\(error.localizedDescription)"
            throw error
        }
    }

    public func importHistory(from url: URL) async throws {
        let accessing = url.startAccessingSecurityScopedResource()
        defer { if accessing { url.stopAccessingSecurityScopedResource() } }
        do {
            guard !persistenceBlocked else { throw HistoryError.storageUnavailable }
            let snapshot = try await Task.detached(priority: .utility) {
                try HistoryArchive.read(from: url)
            }.value
            try Task.checkCancellation()
            try await protectHistory(reason: "before-import")
            // 解析全部成功后才合并，非法输入不会留下部分记录或收藏夹。
            var mergedCollections = collections
            var collectionMapping: [UUID: UUID] = [:]
            for var collection in snapshot.collections {
                let originalID = collection.id
                if syncState.records["collection-\(collection.id.uuidString)"]?.deleted == true {
                    collection.id = UUID()
                }
                if let existing = mergedCollections.first(where: { $0.id == collection.id || $0.name.localizedCaseInsensitiveCompare(collection.name) == .orderedSame }) {
                    collectionMapping[originalID] = existing.id
                } else {
                    mergedCollections.append(collection)
                    collectionMapping[originalID] = collection.id
                }
            }
            var knownIDs = Set(items.map(\.id))
            var knownContent = Set(items.map(HistoryArchive.contentKey))
            var incoming: [ClipItem] = []
            for var item in snapshot.items {
                if syncState.records["item-\(item.id.uuidString)"]?.deleted == true { item.id = UUID() }
                let key = HistoryArchive.contentKey(item)
                // 相同 ID 或内容均保留本机版本，包括用户修改过的收藏夹和固定状态。
                guard !knownIDs.contains(item.id), !knownContent.contains(key) else { continue }
                knownIDs.insert(item.id)
                knownContent.insert(key)
                item.collectionID = item.collectionID.flatMap { collectionMapping[$0] }
                incoming.append(item)
            }
            guard items.count + incoming.count <= 20_000, mergedCollections.count <= 1_000 else {
                throw HistoryError.historyTooLarge
            }
            let combinedUnpinnedBytes = (items + incoming).filter { !$0.isPinned }
                .reduce(0) { $0 + HistoryArchive.payloadBytes($1) }
            guard combinedUnpinnedBytes <= Self.maximumUnpinnedPayloadBytes else {
                throw HistoryError.archiveTooLarge
            }
            // 不套用自动清理，导入不能删除现有历史。必要时增大条数上限来容纳合并结果。
            isLoading = true
            maxItems = max(maxItems, items.count + incoming.count)
            isLoading = false
            collections = mergedCollections
            items.append(contentsOf: incoming)
            items.sort { $0.lastCopiedAt > $1.lastCopiedAt }
            save()
            if let message = await writer.pendingWriteError() { throw HistoryError.writeFailed(message) }
            lastAction = "已导入 \(incoming.count) 条记录，跳过 \(snapshot.items.count - incoming.count) 条重复记录"
        } catch {
            errorMessage = "导入失败：\(error.localizedDescription)"
            throw error
        }
    }

    public func updateText(_ item: ClipItem, text: String) {
        guard !text.isEmpty, text.utf8.count <= Self.maximumPayloadBytes else { return }
        guard let index = items.firstIndex(where: { $0.id == item.id }), [.text, .link].contains(items[index].kind) else { return }
        items[index].text = text
        items[index].kind = Self.kind(for: text)
        // 编辑后的字符串不再对应旧富文本，避免粘贴时出现未编辑的内容。
        items[index].rtfData = nil
        save()
    }

    public func filteredItems(query: String, kind: ClipKind? = nil, collectionID: UUID? = nil, pinnedOnly: Bool = false) -> [ClipItem] {
        let words = query.split(whereSeparator: \.isWhitespace).map(String.init)
        return items.filter { item in
            guard kind == nil || item.kind == kind,
                  collectionID == nil || item.collectionID == collectionID,
                  !pinnedOnly || item.isPinned else { return false }
            guard !words.isEmpty else { return true }
            let searchText = [item.text, item.title, item.sourceApp, item.sourceBundleID, item.filePaths.joined(separator: " ")].joined(separator: "\n")
            return words.allSatisfy { searchText.range(of: $0, options: [.caseInsensitive, .diacriticInsensitive]) != nil }
        }
    }

    public func isExcluded(bundleID: String) -> Bool {
        let identifier = bundleID.lowercased()
        guard !identifier.isEmpty else { return false }
        if Self.passwordManagerBundleIDs.contains(identifier) || Self.passwordManagerPrefixes.contains(where: identifier.hasPrefix) {
            return true
        }
        return excludedBundleIDs.components(separatedBy: CharacterSet(charactersIn: ",;\n\r"))
            .map { $0.trimmingCharacters(in: .whitespacesAndNewlines).lowercased() }
            .filter { !$0.isEmpty }
            .contains { rule in
                rule.hasSuffix(".*") ? identifier.hasPrefix(String(rule.dropLast())) : identifier == rule
            }
    }

    /// 等待已排队的磁盘写入完成，用于退出和自动化验证。
    public func flushPendingSaves() async {
        await writer.flush()
    }

    public func refreshBackups() async {
        let backupStore = LocalBackupStore(directory: backupDirectory)
        do {
            backups = try await Task.detached(priority: .utility) { try backupStore.list() }.value
        } catch { backupError = error.localizedDescription }
    }

    public func createBackup() async {
        do {
            guard !persistenceBlocked else { throw HistoryError.storageUnavailable }
            try await protectHistory(reason: "manual")
            backupError = nil
            lastAction = "已创建本地备份"
            await refreshBackups()
        } catch { backupError = error.localizedDescription }
    }

    /// Recovery merges missing content and keeps current edits. A corrupt primary is preserved separately.
    public func restoreBackup(_ backup: LocalBackupInfo) async {
        do {
            let backupStore = LocalBackupStore(directory: backupDirectory)
            try await Task.detached(priority: .utility) {
                guard try backupStore.list().contains(where: { $0.url == backup.url }) else {
                    throw HistoryError.invalidFile("请选择此应用的本地备份")
                }
                _ = try HistoryArchive.read(from: backup.url)
            }.value
            if persistenceBlocked {
                await writer.flush()
                let damaged = historyFileURL
                let preserved = directory.appendingPathComponent("history-corrupt-\(UUID().uuidString).json")
                try FileManager.default.copyItem(at: damaged, to: preserved)
                // Keep unsaved records captured since the load failure, then merge the backup below.
                persistenceBlocked = false
                errorMessage = nil
            }
            // Imported archives never restore device identity, cloud consent or account binding.
            try await importHistory(from: backup.url)
            lastAction = "已合并恢复备份，当前记录和编辑已保留"
        } catch { backupError = "恢复失败：\(error.localizedDescription)" }
        await refreshBackups()
    }

    private func protectHistory(reason: String) async throws {
        let snapshot = currentSnapshot()
        let backupStore = LocalBackupStore(directory: backupDirectory)
        do {
            try await writer.backup(snapshot, using: backupStore, reason: reason)
        } catch {
            throw HistoryError.writeFailed("保护备份失败：\(error.localizedDescription)")
        }
    }

    public func startBackgroundServices() {
        guard syncTimer == nil else { return }
        let timer = Timer(timeInterval: 60, repeats: true) { [weak self] _ in
            Task { @MainActor [weak self] in
                guard let self, Date() >= self.retrySyncAfter else { return }
                await self.synchronizeNow()
            }
        }
        syncTimer = timer
        RunLoop.main.add(timer, forMode: .common)
        Task { [weak self] in
            await self?.backfillSourceIcons()
            await self?.refreshBackups()
            await self?.synchronizeNow()
        }
    }

    private func sourceIconData(for bundleID: String) -> Data? {
        guard !bundleID.isEmpty, let data = sourceIconProvider(bundleID), !data.isEmpty,
              data.count <= HistoryArchive.maximumSourceIconBytes else { return nil }
        return data
    }

    /// 旧历史按来源应用补齐图标；逐个让出主线程，且不覆盖已经保存的快照。
    func backfillSourceIcons() async {
        guard !persistenceBlocked else { return }
        let bundleIDs = Set(items.filter { $0.sourceIconData == nil }.map(\.sourceBundleID))
        var icons: [String: Data] = [:]
        for bundleID in bundleIDs where !bundleID.isEmpty {
            await Task.yield()
            guard !Task.isCancelled else { return }
            icons[bundleID] = sourceIconData(for: bundleID)
        }
        var totalBytes = items.reduce(0) { $0 + HistoryArchive.payloadBytes($1) }
        var ordinaryBytes = items.filter { !$0.isPinned }.reduce(0) { $0 + HistoryArchive.payloadBytes($1) }
        var changed = false
        for index in items.indices where items[index].sourceIconData == nil {
            guard let data = icons[items[index].sourceBundleID],
                  totalBytes + data.count <= HistoryArchive.maximumCombinedPayloadBytes,
                  items[index].isPinned || ordinaryBytes + data.count <= Self.maximumUnpinnedPayloadBytes else { continue }
            items[index].sourceIconData = data
            totalBytes += data.count
            if !items[index].isPinned { ordinaryBytes += data.count }
            changed = true
        }
        if changed { save() }
    }

    public func stopBackgroundServices() {
        syncTimer?.invalidate()
        syncTimer = nil
        syncGeneration += 1
        activeSyncTask?.cancel()
    }

    public func setCloudSyncEnabled(_ enabled: Bool) async {
        if enabled, let message = cloudConfigurationError {
            syncStatus = message
            return
        }
        syncGeneration += 1
        activeSyncTask?.cancel()
        cloudSyncEnabled = enabled
        syncTransport = nil
        if !enabled {
            syncStatus = "iCloud 同步已关闭，本机和云端数据均保留"
        } else {
            // Explicit enabling acknowledges the currently signed-in account.
            cloudAccountID = nil
            retrySyncAfter = .distantPast
            syncStatus = "等待连接 iCloud"
        }
        save()
        if enabled { await synchronizeNow() }
    }

    public func synchronizeNow() async {
        guard cloudSyncEnabled, !isSyncing, !persistenceBlocked else { return }
        do {
            if syncTransport == nil { syncTransport = try CloudKitTransport() }
            guard let syncTransport else { return }
            try await synchronize(using: syncTransport)
        } catch is CancellationError {
            // Disabling sync already publishes the appropriate status.
        } catch {
            if !syncStatus.hasPrefix("同步未完成：") { syncStatus = "同步未完成：\(error.localizedDescription)" }
        }
    }

    /// The injected transport keeps reconciliation testable without an Apple account or network.
    func synchronize(using transport: any ClipboardSyncTransport) async throws {
        guard activeSyncTask == nil, !persistenceBlocked else { return }
        isSyncing = true
        let task = Task { try await self.performSynchronization(using: transport) }
        activeSyncTask = task
        defer {
            activeSyncTask = nil
            isSyncing = false
        }
        try await withTaskCancellationHandler {
            try await task.value
        } onCancel: {
            task.cancel()
        }
    }

    private func performSynchronization(using transport: any ClipboardSyncTransport) async throws {
        try Task.checkCancellation()
        let generation = syncGeneration
        syncStatus = "正在同步…"
        do {
            let account = try await transport.accountID()
            guard generation == syncGeneration else { return }
            if let cloudAccountID, cloudAccountID != account { throw SyncError.accountChanged }
            if cloudAccountID == nil {
                cloudAccountID = account
                save()
                if let message = await writer.pendingWriteError() { throw HistoryError.writeFailed(message) }
            }
            let remote = try await transport.fetch()
            guard generation == syncGeneration else { return }
            guard try await transport.accountID() == account else { throw SyncError.accountChanged }
            guard generation == syncGeneration else { return }
            // Backup before applying any remote mutation. Re-read local state after the await.
            let initial = try SyncMerge.merge(syncState.entries(items: items, collections: collections), remote)
            if initial != syncState.entries(items: items, collections: collections).sorted(by: { $0.key < $1.key }) {
                try await protectHistory(reason: "before-sync")
            }
            guard generation == syncGeneration else { return }
            reconcileSyncState()
            let merged = try SyncMerge.merge(syncState.entries(items: items, collections: collections), remote)
            let mergedCollections = merged.compactMap(\.collection).sorted { $0.id.uuidString < $1.id.uuidString }
            let validCollections = Set(mergedCollections.map(\.id))
            var mergedItems = merged.compactMap(\.item) + items.filter { $0.kind == .file }
            for index in mergedItems.indices where mergedItems[index].collectionID.map({ !validCollections.contains($0) }) == true {
                mergedItems[index].collectionID = nil
            }
            mergedItems.sort {
                $0.lastCopiedAt == $1.lastCopiedAt ? $0.id.uuidString < $1.id.uuidString : $0.lastCopiedAt > $1.lastCopiedAt
            }
            var candidate = currentSnapshot()
            candidate.items = mergedItems
            candidate.collections = mergedCollections
            try HistoryArchive.validate(candidate)
            items = mergedItems
            collections = mergedCollections
            syncState.accept(merged)
            syncBaselineItems = merged.compactMap(\.item)
            syncBaselineCollections = mergedCollections
            // Retention is a shared deletion policy. Tombstones prevent an offline Mac resurrecting it.
            applyLimits()
            save()
            let remoteMap = Dictionary(remote.map { ($0.key, $0) }, uniquingKeysWith: { first, _ in first })
            let outgoing = syncState.entries(items: items, collections: collections).filter { remoteMap[$0.key] != $0 }
            if let message = await writer.pendingWriteError() { throw HistoryError.writeFailed(message) }
            guard generation == syncGeneration else { return }
            guard try await transport.accountID() == account else { throw SyncError.accountChanged }
            guard generation == syncGeneration else { return }
            try await transport.push(outgoing)
            guard generation == syncGeneration else { return }
            lastSyncDate = Date()
            syncFailures = 0
            retrySyncAfter = .distantPast
            syncStatus = "已同步"
            await refreshBackups()
        } catch {
            if generation == syncGeneration {
                syncFailures = min(syncFailures + 1, 8)
                let delay = max(Self.cloudRetryDelay(error), min(pow(2, Double(syncFailures)) * 15, 3_600))
                retrySyncAfter = Date().addingTimeInterval(delay)
                syncStatus = "同步未完成：\(error.localizedDescription)。本机更改已保留，将自动重试"
            }
            throw error
        }
    }

    private func pollClipboard() {
        guard isMonitoring else { return }
        if Date().timeIntervalSince(lastPrunedAt) > 60 {
            let count = items.count
            applyLimits()
            if items.count != count { save() }
        }
        captureIfChanged()
    }

    /// 立即采集轮询尚未发现的剪贴板变化，避免内容在下一次轮询前被覆盖。
    public func captureIfChanged() {
        guard isMonitoring, pasteboard.changeCount != lastChangeCount else { return }
        captureCurrentClipboard()
    }

    private func readImageData() -> Data? {
        for type in [NSPasteboard.PasteboardType.png, .tiff, NSPasteboard.PasteboardType("public.jpeg")] {
            if let data = pasteboard.data(forType: type), !data.isEmpty { return data }
        }
        return nil
    }

    private static func imageType(for data: Data) -> NSPasteboard.PasteboardType {
        if data.starts(with: [0x89, 0x50, 0x4E, 0x47]) { return .png }
        if data.starts(with: [0xFF, 0xD8, 0xFF]) { return NSPasteboard.PasteboardType("public.jpeg") }
        return .tiff
    }

    private static func kind(for text: String) -> ClipKind {
        let trimmed = text.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !trimmed.contains(where: \.isWhitespace),
              let url = URL(string: trimmed), let scheme = url.scheme?.lowercased(),
              ["http", "https", "ftp", "mailto", "tel"].contains(scheme) else { return .text }
        if ["http", "https", "ftp"].contains(scheme), url.host == nil { return .text }
        return .link
    }

    private static func hasSameContent(_ left: ClipItem, _ right: ClipItem) -> Bool {
        guard left.kind == right.kind else { return false }
        switch left.kind {
        case .text, .link: return left.text == right.text
        case .image: return left.imageData == right.imageData
        case .file: return left.filePaths.sorted() == right.filePaths.sorted()
        }
    }

    /// 按最近使用时间应用之前推迟的排序；相同时间保持原有相对顺序。
    public func applyDeferredReorder() {
        guard !deferredReorderIDs.isEmpty else { return }
        let ranks = Dictionary(deferredReorderIDs.enumerated().map { ($1, $0) }, uniquingKeysWith: { first, _ in first })
        deferredReorderIDs = []
        let sorted = items.enumerated().sorted { left, right in
            guard left.element.lastCopiedAt == right.element.lastCopiedAt else {
                return left.element.lastCopiedAt > right.element.lastCopiedAt
            }
            let leftRank = ranks[left.element.id] ?? .max, rightRank = ranks[right.element.id] ?? .max
            return leftRank == rightRank ? left.offset < right.offset : leftRank < rightRank
        }.map(\.element)
        guard sorted.map(\.id) != items.map(\.id) else { return }
        items = sorted
        save()
    }

    private func markCopied(_ item: ClipItem, reorder: Bool = true) {
        if let index = items.firstIndex(where: { $0.id == item.id }) {
            if reorder {
                var updated = items.remove(at: index)
                updated.lastCopiedAt = Date()
                items.insert(updated, at: 0)
            } else {
                items[index].lastCopiedAt = Date()
                deferredReorderIDs.removeAll { $0 == item.id }
                deferredReorderIDs.insert(item.id, at: 0)
            }
            save()
        }
        lastAction = "已复制到剪贴板"
    }

    private func settingsChanged() {
        guard !isLoading else { return }
        applyLimits()
        save()
    }

    private func applyLimits() {
        lastPrunedAt = Date()
        if retentionDays > 0 {
            let threshold = Date().addingTimeInterval(-Double(retentionDays) * 86_400)
            items.removeAll { !$0.isPinned && $0.lastCopiedAt < threshold }
        }
        let pinnedCount = items.filter(\.isPinned).count
        let unpinnedAllowance = max(0, maxItems - pinnedCount)
        var unpinnedCount = 0
        items.removeAll { item in
            guard !item.isPinned else { return false }
            unpinnedCount += 1
            return unpinnedCount > unpinnedAllowance
        }
        var retainedBytes = 0
        items.removeAll { item in
            guard !item.isPinned else { return false }
            retainedBytes += HistoryArchive.payloadBytes(item)
            return retainedBytes > Self.maximumUnpinnedPayloadBytes
        }
    }

    private func loadHistory() {
        guard FileManager.default.fileExists(atPath: historyFileURL.path) else { return }
        do {
            // The primary may contain legacy pinned content beyond the export/sync budget.
            // Do not reject a library the local writer was previously allowed to persist.
            let snapshot = try JSONDecoder().decode(HistorySnapshot.self, from: Data(contentsOf: historyFileURL))
            try HistoryArchive.validate(snapshot, enforceArchiveLimits: false)
            items = snapshot.items.sorted { $0.lastCopiedAt > $1.lastCopiedAt }
            collections = snapshot.collections
            maxItems = snapshot.maxItems
            excludedBundleIDs = snapshot.excludedBundleIDs
            retentionDays = snapshot.retentionDays
            monitoringPreference = snapshot.monitoringEnabled ?? true
            syncState = snapshot.syncState ?? ClipboardSyncState()
            try syncState.validate(enforceRecordLimit: false)
            cloudSyncEnabled = snapshot.cloudSyncEnabled ?? false
            cloudAccountID = snapshot.cloudAccountID
            automaticBackupEnabled = snapshot.automaticBackupEnabled ?? true
            backupIntervalHours = snapshot.backupIntervalHours ?? 6
            syncStatus = cloudSyncEnabled ? "等待同步" : "iCloud 同步未开启"
        } catch {
            // 读取失败后禁止覆盖原文件，保留数据供用户恢复。
            persistenceBlocked = true
            errorMessage = "无法读取历史记录，已保留原文件并暂停写入：\(error.localizedDescription)"
        }
    }

    private func save() {
        guard !isLoading, !persistenceBlocked else { return }
        reconcileSyncState()
        saveRevision += 1
        let revision = saveRevision
        let snapshot = currentSnapshot()
        writer.write(snapshot, to: historyFileURL) { [weak self] message, backupMessage in
            Task { @MainActor [weak self] in
                guard let self, revision >= self.lastCompletedRevision else { return }
                self.lastCompletedRevision = revision
                self.backupError = backupMessage
                if let message {
                    self.errorMessage = "历史记录保存失败：\(message)"
                } else if self.errorMessage?.hasPrefix("历史记录保存失败：") == true {
                    self.errorMessage = nil
                }
            }
        }
    }

    private func currentSnapshot() -> HistorySnapshot {
        HistorySnapshot(version: 1, items: items, collections: collections, maxItems: maxItems,
                        excludedBundleIDs: excludedBundleIDs, retentionDays: retentionDays,
                        monitoringEnabled: monitoringPreference, syncState: syncState,
                        cloudSyncEnabled: cloudSyncEnabled, cloudAccountID: cloudAccountID,
                        automaticBackupEnabled: automaticBackupEnabled, backupIntervalHours: backupIntervalHours)
    }

    private func reconcileSyncState() {
        syncState.reconcile(items: items, collections: collections,
                            previousItems: syncBaselineItems, previousCollections: syncBaselineCollections)
        syncBaselineItems = items
        syncBaselineCollections = collections
        // Before this installation has ever joined iCloud, no remote peer can hold
        // its deleted UUIDs. Avoid accumulating tombstones in a local-only library.
        if cloudAccountID == nil && !cloudSyncEnabled {
            syncState.records = syncState.records.filter { !$0.value.deleted }
        }
    }

    static func cloudRetryDelay(_ error: Error, depth: Int = 0) -> TimeInterval {
        guard depth < 8, let cloudError = error as? CKError else { return 0 }
        let children = cloudError.partialErrorsByItemID?.values.map { cloudRetryDelay($0, depth: depth + 1) } ?? []
        return max(cloudError.retryAfterSeconds ?? 0, children.max() ?? 0)
    }
}

/// 串行写入保证较早的快照不会覆盖较新的编辑，JSON 编码也在后台执行。
private final class HistoryWriter: @unchecked Sendable {
    private let queue = DispatchQueue(label: "app.xpastepal.history", qos: .utility)
    private var lastError: String?

    func write(_ snapshot: HistorySnapshot, to url: URL, completion: @escaping @Sendable (String?, String?) -> Void) {
        queue.async {
            do {
                try HistoryArchive.write(snapshot, to: url, enforceArchiveLimit: false)
                self.lastError = nil
                var backupMessage: String?
                if snapshot.automaticBackupEnabled ?? true {
                    do {
                        let backups = LocalBackupStore(directory: url.deletingLastPathComponent().appendingPathComponent("Backups"))
                        try backups.create(snapshot, reason: "automatic",
                                           minimumInterval: Double(snapshot.backupIntervalHours ?? 6) * 3_600)
                    } catch { backupMessage = "自动备份失败：\(error.localizedDescription)" }
                }
                completion(nil, backupMessage)
            } catch {
                self.lastError = error.localizedDescription
                completion(error.localizedDescription, nil)
            }
        }
    }

    func backup(_ snapshot: HistorySnapshot, using store: LocalBackupStore, reason: String) async throws {
        try await withCheckedThrowingContinuation { (continuation: CheckedContinuation<Void, Error>) in
            queue.async {
                do {
                    try store.create(snapshot, reason: reason)
                    continuation.resume()
                } catch { continuation.resume(throwing: error) }
            }
        }
    }

    func flush() async {
        await withCheckedContinuation { continuation in
            queue.async { continuation.resume() }
        }
    }

    func pendingWriteError() async -> String? {
        await withCheckedContinuation { continuation in
            queue.async { continuation.resume(returning: self.lastError) }
        }
    }
}
